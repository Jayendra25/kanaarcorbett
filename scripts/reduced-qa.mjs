import puppeteer from "puppeteer-core";
const browser = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: "new", args: ["--hide-scrollbars"] });
const page = await browser.newPage();
await page.setViewport({ width: 1440, height: 1000 });
await page.emulateMediaFeatures([{ name: "prefers-reduced-motion", value: "reduce" }]);
await page.goto("http://localhost:3000/", { waitUntil: "networkidle2" });
await new Promise((r) => setTimeout(r, 1200));
console.log("reduced:", await page.evaluate(() => ({ data: document.documentElement.dataset.intro, intro: !!document.querySelector(".intro"), locked: document.body.classList.contains("intro-lock"), storyH: Math.round(document.querySelector(".story").getBoundingClientRect().height), sticky: getComputedStyle(document.querySelector(".story__sticky")).display, mobile: getComputedStyle(document.querySelector(".story__mobile")).display, scrollH: document.documentElement.scrollHeight })));
const y = await page.evaluate(() => document.querySelector("#corbett").getBoundingClientRect().top + window.scrollY);
await page.evaluate((y) => window.scrollTo(0, y), y);
await new Promise((r) => setTimeout(r, 1000));
await page.screenshot({ path: ".shots/reduced-corbett.png" });
await browser.close();
