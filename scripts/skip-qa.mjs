import puppeteer from "puppeteer-core";
const browser = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: "new", args: ["--hide-scrollbars"] });
const page = await browser.newPage();
await page.setViewport({ width: 1440, height: 1000 });
await page.goto("http://localhost:3000/?intro=1", { waitUntil: "networkidle2" });
await new Promise((r) => setTimeout(r, 900));
await page.click(".intro__skip");
await new Promise((r) => setTimeout(r, 900));
console.log("skip:", await page.evaluate(() => ({ data: document.documentElement.dataset.intro, present: !!document.querySelector(".intro"), locked: document.body.classList.contains("intro-lock"), stored: sessionStorage.getItem("kanaar-intro") })));
await page.goto("http://localhost:3000/?intro=1", { waitUntil: "networkidle2" });
await new Promise((r) => setTimeout(r, 900));
await page.keyboard.press("Escape");
await new Promise((r) => setTimeout(r, 900));
console.log("escape:", await page.evaluate(() => ({ data: document.documentElement.dataset.intro, present: !!document.querySelector(".intro"), locked: document.body.classList.contains("intro-lock") })));
await browser.close();
